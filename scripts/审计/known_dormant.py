"""已知「够不着」的规则登记表。

【为什么需要这张表】
实测台判一条规则好不好，只看「喂它一段真实报错，它能不能自己命中」。
但有几条规则**按设计就命中不了**，原因不在规则本身，而在别处（工具链行为、应用设计）。
它们和「规则写错了」在实测台眼里长得一模一样，都是 ✗。

不分开的后果是：实测台永远挂着几条红，看久了就没人看了 ——
真正的回归（比如某个 pattern 被改坏）混在里面，再也认不出来。

【因此这张表有两条纪律】
  1. 每条都必须写清「为什么够不着」和「什么情况下该回来重测」。
     写不出来的，就不是「已知够不着」，是「没查明」—— 那应该留在有问题清单里。
  2. 进了这张表的规则，实测台**不算它命中，也不算它失败**，单独计一栏并打印出来。
     绝不静默跳过：静默跳过等于把问题藏起来，比红着还糟。
"""

