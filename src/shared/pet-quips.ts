/**
 * 32 位散列（murmur3 的 finalizer：两次乘 + 折返，雪崩性质足够挑台词用）。
 * 【为什么自己写散列】见文件头：要的是「同 seed 同句」这个可测的承诺，
 * 而 Math.random 给不了；引入一个依赖只为一个取模更不值。
 */
function mix32(x: number): number {
  let h = x | 0
  h = Math.imul(h ^ (h >>> 16), 0x45d9f3b)
  h = Math.imul(h ^ (h >>> 16), 0x45d9f3b)
  return (h ^ (h >>> 16)) >>> 0
}

/**
 * 把任意有限数折进 32 位。**高位也要参与**：Date.now() 这种时间戳超过 2^32，
 * 只取低 32 位的话，"步长正好 2^32 的倍数"的种子会整批落到同一句上。
 * 小数部分按截断处理（seed 的约定是整数：时间戳、第几次、自增刻度）。
 */
function foldSeed(seed: number): number {
  const lo = seed | 0
  const hi = Math.floor(seed / 4294967296) | 0
  return (lo ^ Math.imul(hi, 0x85ebca6b)) >>> 0
}

/**
 * 场景盐（场景名过一遍 FNV-1a）。**同 seed 不同场景要错开** —— 不然调用方
 * 拿「第几次点击」当 seed 时，七个场景会齐刷刷挑中各自池子里的同一序号。
 */
function sceneSalt(scene: QuipScene): number {
  let h = 0x811c9dc5
  for (let i = 0; i < scene.length; i++) h = Math.imul(h ^ scene.charCodeAt(i), 0x01000193)
  return h >>> 0
}

/**
 * 没给 seed 时的种子 = 时间戳 ^ 自增刻度。同一个毫秒里连点两下也要换一句
 * （光靠 Date.now() 会撞成同一句）。**只有这条路径动计数器**：给了 seed 的
 * 调用完全绕开它，于是"之前说过几句"污染不了任何一次带 seed 的调用 ——
 * 测试要的确定性全靠这条。
 */
let autoTicks = 0
function autoSeed(): number {
  autoTicks = (autoTicks + 1) >>> 0
  return (Date.now() ^ Math.imul(autoTicks, 0x9e3779b1)) >>> 0
}

/**
 * 挑一句台词。规则：
 *   ① 给了 `seed` → **确定**（同 seed、同场景、同 recent，必得同句）；
 *   ② `recent`（最近说过的 text）里的**不选**；整池都被命中 → 忽略 recent
 *      兜底（宁可说重复的，也不许这里死循环或返回空）；
 *   ③ 挑不中、或挑到空台词 → **抛错**，绝不静默回退第一条（静默回退会把
 *      "池子数据坏了"藏成"台词老重复"，而后者没人会去查）。
 */
export function pickQuip(scene: QuipScene, opts?: { seed?: number; recent?: string[] }): Quip {
  const pool = QUIP_POOL[scene]
  // 运行时兜底：TS 联合挡不住从 IPC 那边漏进来的野字符串。宁可当场报错，
  // 也不许悄悄换成一个"默认场景"——那会让别处的一个拼写错误长成
  // 「桌宠偶尔不说话」这种查不动的现象。
  if (!pool || pool.length === 0) {
    throw new Error(`pet-quips: 场景 ${String(scene)} 没有台词（池子空或场景名不在册）`)
  }

  const recent = opts?.recent
  const seen = recent && recent.length > 0 ? new Set(recent) : null
  let candidates: readonly Quip[] = pool
  if (seen) {
    const fresh = pool.filter((q) => !seen.has(q.text))
    if (fresh.length > 0) candidates = fresh
  }

  const seed = opts?.seed ?? autoSeed()
  // NaN / Infinity 不做"修正成 0"的静默兜底：种子算错了要让调用方知道，
  // 悄悄修正只会让他以为算对了（同 ③ 的口径）。
  if (!Number.isFinite(seed)) {
    throw new Error('pet-quips: seed 必须是有限数')
  }

  const hit = candidates[mix32(foldSeed(seed) ^ sceneSalt(scene)) % candidates.length]
  if (!hit || hit.text.trim() === '') {
    throw new Error(`pet-quips: 场景 ${scene} 挑到了空台词（池子数据坏了）`)
  }

  // 返回**副本**：池子是全进程共享的常量，谁把返回值改脏都别牵连下一句
  return { ...hit }
}
