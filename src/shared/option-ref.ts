/**
 * 解析里有没有「按字母 / 按位置」指代选项？
 *
 * 【为什么要有这个文件】
 * 组卷会洗选项顺序（`quiz-paper.ts` 的 `shuffleOptions`），但解析是一段散文：
 * 程序搬得动 `answer` 下标，搬不动「D 说的…」「第二项也不对」。
 * 2026-10-21 宣传片里暴露的正是这个 —— 源题正确答案在 D，解析写「D 说的顺序与牵连」；
 * 洗过之后正确项到了 B，学员看到的是「选了 B，解析却在讲 D」。
 *
 * 【三种用法，判据只有这一份】
 *   · 内置题 / 题库题：`quiz-paper.ts` 见到这种解析就**不洗这道题的选项**
 *     （保持原文顺序，解析自然还对得上）。这是兜底 —— 任何存量或新内容
 *     都不会在屏幕上错位，代价只是这道题少一点「防背位置」的效果。
 *   · AI 题：`ai-question.ts` **直接丢掉**（提示词里也明令禁止这么写）。
 *   · 内容闸门：`__tests__/option-ref.test.ts` 扫全部 questions.json，
 *     命中即单测变红，逼新内容一开始就写「引原话」而不是「引编号」。
 *
 * 【两档判据：宽口径 vs 硬判据】
 *   兜底和 AI 收题用 `findOptionRefs`（宽口径）：宁可误判。误判只是不洗牌 / 少收一题。
 *   内容闸门用 `findHardOptionRefs`（硬判据）：只收「几乎不可能是别的东西」的写法。
 *   「第N句 / 前两项」这类词多半在说选项，但也可能在说课文句子、公式里的项；
 *   运行时照样兜底，只是不逼作者改写正常句子。
 *
 * 【判据故意偏「宁可误判」】
 * 误判的代价 = 这道题不洗选项（少一点防背位置的效果）；
 * 漏判的代价 = 解析和选项在学员眼前对不上（比背位置严重得多）。
 * 但也不能宽到把「C 语言」「C++」「汉诺塔的 A→C」当成选项 ——
 * 那会把一整批正常题冻住。所以下面每条正则都写清了它认什么、不认什么。
 */

/*
 * 选项字母：大写 `A-F` 与全角 `Ａ-Ｆ` 进所有判据；小写 `a-f` **只进
 * 带「选项/答案」前缀的写法和宽口径**。
 *
 * 2026-10-21 审计要求补小写/全角（`选项 a 和选项 c 都对`、`正确的是 c`）。
 * 但全量内容实测：把小写放进通用字母族后，公式里的 `(a)`、`a, b`、`f`
 * 立刻被硬判据误伤 8 处 —— 硬判据是要逼作者改内容的，误伤不能接受。
 * 所以小写只在两种无歧义的位置出现：前面挂着「选项/答案/选」，
 * 或者只进宽口径（运行时兜底 / AI 收题，误判只是不洗牌）。
 */
const LETTERS = 'A-FＡ-Ｆ'
const LOWER_LETTERS = 'a-f'
/** 字母后面不许接的东西：英文/全角字母与加号（`C++` 的第二个 C 后面是 +）。 */
const NOT_LETTER_AHEAD = '(?![A-Za-z+＋Ａ-Ｚａ-ｚ])'
/** 字母前面不许接的东西：英文/全角字母、箭头（汉诺塔的 `A→C`）。 */
const NOT_LETTER_BEHIND = '(?<![A-Za-zＡ-Ｚａ-ｚ→←↑↓>])'
/** 圈号：`选项①说反了`。只在宽口径里用。 */
const CIRCLED = '[①②③④⑤⑥⑦⑧⑨⑩]'

/**
 * 「A、B、C」「A 和 D」「C、D」——**至少两个**字母才认。
 *
 * 单字母的组合式在中文里太容易撞上语言名：`C、C++、Java` 的第一个 `C`
 * 后面也挂着一个顿号。要求第二个字母也得是 `A-F` 且后面不跟字母/加号，
 * 才能把 `C、C++` 和 `C、D` 分开。
 *
 * `(?<![→←↑↓>])` 挡的是流程/走法记号：汉诺塔解析里的 `A→C、A→B`，
 * `C` 前面是箭头，不是选项。
 */
const LETTER_RUN = new RegExp(
  `(?<![A-Za-zＡ-Ｚａ-ｚ→←↑↓>])[${LETTERS}]${NOT_LETTER_AHEAD}(?:\\s*(?:或者|或|和|与|、|,|，|/|／)\\s*[${LETTERS}]${NOT_LETTER_AHEAD})+`,
  'g'
)

/**
 * 「D 说的」「A 是」「C 说得不对」——单字母 + 一个谓语。
 *
 * 只认 `说 / 是 / 不是 / 才`。**不认** `也 / 都`：
 * 「写岔了 C 也不拦你」是语言 C，不是选项 C；而真正的多选项指代
 * （「A、B、C 都不是」）已经被 `LETTER_RUN` 整段抓住了，不需要这里补刀。
 *
 * 仍会误判「C 是编译型语言」这类句子 —— 代价只是这道题不洗选项，可以接受。
 */
const LETTER_NARRATIVE = new RegExp(
  `${NOT_LETTER_BEHIND}[${LETTERS}]${NOT_LETTER_AHEAD}\\s*(?=(?:说|是|不是|才|正确|错误|符合|不符))`,
  'g'
)

/**
 * 小写的「a 和 c 都对」「c 说的是另一回事」——**只进宽口径**。
 *
 * 公式里的 `a, b`、`f 是…` 跟选项写法长得一模一样，放进硬判据会逼内容作者
 * 去改数学/代码解释（2026-10-21 全量实测 8 处误伤）。运行时判错只是这道题
 * 不洗牌、AI 判错只是少收一题，代价可以接受。
 */
const LETTER_RUN_LOWER = new RegExp(
  `(?<![A-Za-z])[${LOWER_LETTERS}](?![A-Za-z])(?:\\s*(?:或者|或|和|与|、|,|，|/|／)\\s*[${LOWER_LETTERS}](?![A-Za-z]))+`,
  'g'
)
const LETTER_NARRATIVE_LOWER = new RegExp(
  `(?<![A-Za-z])[${LOWER_LETTERS}](?![A-Za-z])\\s*(?=(?:说|是|不是|才|正确|错误|符合|不符))`,
  'g'
)

/**
 * 「C 对」「D 错」——单字母 + 单个判断字。
 *
 * 只在判断字**后面就是标点/空白/结尾**时才认：「C 对比一下」是拿 C 语言作比较，
 * 不是选项 C。单独把「对/错」放进 `LETTER_NARRATIVE` 会把这种正常句子冻住。
 */
const LETTER_VERDICT_BARE = new RegExp(
  `${NOT_LETTER_BEHIND}[${LETTERS}]${NOT_LETTER_AHEAD}\\s*(?=[对错](?=[。！？；：，、\\s]|$))`,
  'g'
)

/** 「ABD 都不对」「ABC 全错」——连写的选项字母 + 整体判断词 */
const LETTER_CONCAT = new RegExp(
  `${NOT_LETTER_BEHIND}[${LETTERS}]{2,4}${NOT_LETTER_AHEAD}\\s*(?=(?:[一二两三四五六七八九十\\d]+\\s*个?\\s*)?(?:都|均|全|不|对|错|正确|错误))`,
  'g'
)

/** 「除了 D 都对」「除 C 以外全对」 */
const LETTER_EXCEPT = new RegExp(
  `(?:除了|除)\\s*[${LETTERS}]${NOT_LETTER_AHEAD}\\s*(?:都|均|全|以外|之外)`,
  'g'
)

/** 「（B）」「(C)」——括号里单独一个选项字母 */
const LETTER_PAREN = new RegExp(`[（(]\\s*[${LETTERS}]\\s*[）)]`, 'g')

/**
 * 「正确的是 C」「错误的答案是 D」——判断词做前缀。
 *
 * 只认「判断词 + 是/为」或「判断词 + 选项/答案」两种结构：
 * 「正确的 C 写法」是形容 C 语言，不是选项 C。
 */
const LETTER_JUDGED = new RegExp(
  `(?:(?:正确|错误)(?:的)?(?:选项|答案)?(?:\\s*(?:应该|应|该|就|才|也|都|还))?\\s*(?:是|为)\\s*|(?:正确|错误)的(?:选项|答案)\\s*)[${LETTERS}${LOWER_LETTERS}]${NOT_LETTER_AHEAD}`,
  'g'
)

/** 「选项 A」「答案是 B」「答案选 C」「选 D」——前面带选项词的单字母 */
const LETTER_PREFIX = new RegExp(
  `(?:选项|答案|答|选|应选|要选|该选)(?:\\s*(?:的\\s*)?(?:应该是|应是|应选|应该|就是|要是|要|应|该|是|为|选)\\s*)?\\s*[${LETTERS}${LOWER_LETTERS}]${NOT_LETTER_AHEAD}`,
  'g'
)

/** 「B 项」「A 选项」——字母在后、选项词在前 */
const LETTER_SUFFIX = new RegExp(`${NOT_LETTER_BEHIND}[${LETTERS}]${NOT_LETTER_AHEAD}\\s*(?:选项|项)`, 'g')

/**
 * 「第二项」「第 2、3 个选项」「第三个选项」。
 *
 * 数字允许中文与阿拉伯数字混写；`第 2、3 个选项` 这种合写也要整段抓住，
 * 否则只换掉后半截会造出「第二、『C 的原文』」这种病句。
 *
 * 【它挡不住的一种】`va_start` 的第二项 —— 那是宏的第二个参数，不是选项。
 * 句法上分不出来，只能靠内容侧把话写清楚（2026-10-21 已把那句改成「第二个参数」）。
 */
const ORDINAL = new RegExp(
  `第\\s*(?:[（(]\\s*[一二三四五六七八九十\\d]+\\s*[）)]|[一二三四五六七八九十\\d]+)(?:\\s*[、,，]\\s*第?\\s*(?:[（(]\\s*[一二三四五六七八九十\\d]+\\s*[）)]|[一二三四五六七八九十\\d]+))*(?:\\s*个)?\\s*(?:选项|项)`,
  'g'
)

/**
 * 「第一种」「第二种写法」「第四类做法」——按**种类**点名选项。
 *
 * 2026-10-21 审计抓到：原来两档判据都不认这个族，现网 4 道题（C 函数 /
 * Python 元组字典 / Python 函数进阶 / Python 继承）的解析正用它指代选项，
 * 组卷照常洗牌 —— 反序一洗，解析里的「第一种」正好指到错误项上。
 * 这个项目里选择题的四个选项就是四种写法/做法，「第N种」在解析里几乎只在
 * 说选项，所以进硬判据。已知的误伤面是教材里讲「第一种方法」这种分类
 * （不带 写法/做法 后缀的裸「第N种」）：内容闸门会判红，代价是作者改写一句。
 */
const ORDINAL_KIND = new RegExp(
  `第\\s*(?:[（(]\\s*[一二三四五六七八九十\\d]+\\s*[）)]|[一二三四五六七八九十\\d]+)\\s*(?:种|类|款)(?:写法|做法|方式|思路|情况|说法)?`,
  'g'
)

/*
 * ⚠️ 下面几条带空白的正则，空白一律写进可选组**内部**（`(?:\s*那|这)?`），
 * **不要**写成 `\s*(?:那|这)?\s*`：相邻的两个可空 `\s*` 会让失败路径把
 * 同一串空白反复切分，长空白输入下退化成 n³/n⁴ 回溯。2026-10-21 审计实测
 * 「前 + 800 个空格 + X」在旧写法上要 206 秒 —— 而 AI 解析跑在主进程里、
 * 上限 1000 字，足够触发。`option-ref.test.ts` 末尾有回归用例钉着。
 */

/**
 * 「最后一个选项」「前两个选项」「后一个选项」。
 *
 * `(?<!剩)` 放行「剩下两个选项」：它说的是**补集**，跟顺序无关，
 * 洗不洗都指同样那两项。
 */
const POSITIONAL = new RegExp(
  `(?<!剩)(?:最后|前|后|上|下)(?:\\s*(?:那|这|一|两|几|[一二三四五六七八九十\\d]+))?(?:\\s*个)?\\s*选项`,
  'g'
)

/**
 * 「第三句」「第二条」「最后那个说法」——按**位置**点名一句/一条/一个说法。
 *
 * 这族词在解析里**大多是**在说选项（四个选项就是四句/四条），但也会说课文里的
 * 句子、代码里的行。句法上分不出来，所以归进「宽口径」：宽口径判错只会让这道题
 * 不洗选项（少一点防背位置的效果），不会把正常题弄坏。
 *
 * 【已知不认「第N行」】它在 854 道选择题的解析里出现 25 次，几乎全在说
 * 课文的代码行；扩进宽口径会白冻 25 道题（2026-10-21 全量扫描后决定不加）。
 * 内容侧的纪律：**选项本身是代码行时，解析必须引原话** —— common/05-condition
 * q2 原来写「只有第一行」，就是靠一条误伤句意外冻住才没出错，现已改成
 * 引用 `if fish == 3:`（2026-10-21）。
 */
const ORDINAL_SENTENCE = new RegExp(
  `第\\s*[一二三四五六七八九十\\d]+(?:\\s*[、,，]\\s*第?\\s*[一二三四五六七八九十\\d]+)*(?:\\s*个|\\s*种)?\\s*(?:句|条(?!命令)|说法)`,
  'g'
)

/**
 * 「第三个干扰项」「第二个错项」「第一个错在」——**只可能**在说选项。
 *
 * 「错在」后面常跟内容（「第一个错在『里头的货还在』」），所以它属于硬判据：
 * 内容里出现就说明作者在给选项编号，必须改。
 */
const ORDINAL_FAULT = new RegExp(
  `第\\s*[一二三四五六七八九十\\d]+(?:\\s*个)?\\s*(?:干扰项|错项|错在|是对的|是错的|不对|没错|正确|错误)`,
  'g'
)

/**
 * 「第一个是…」「第二个是…」——不带「选项」二字的序数指代。
 *
 * 只进宽口径：它在说选项，也可能在说课文里的第一个要点/第一行代码。
 * 要求「第N个」**紧接**判断词，「第一个参数是」这类正常句子不会被冻住。
 */
const ORDINAL_NAKED = new RegExp(
  `第\\s*[一二三四五六七八九十\\d]+\\s*个\\s*(?=(?:是|为|就是|才|不|错|对|正确|错误|符合))`,
  'g'
)

/**
 * 「选项 1」「选项二」「答案 2」——中文里偶尔用数字给选项编号。
 *
 * 只认后面紧跟数字且**不是多位数**的写法，避免把「选项 2024」这类正文误伤；
 * 字母编号已由 `LETTER_PREFIX` 管。
 *
 * `答案` 只接**阿拉伯数字**、不接中文数字：中文里的「答案一…」几乎全是
 * 「答案一样大」「答案是一个字都没有」这种正常句子（2026-10-21 全量扫描里
 * 两条硬命中都是这个假阳性）。真要给选项编号，会写「答案是 1」「答案 2」。
 */
const OPTION_NUMBER = new RegExp(
  `(?:选项(?:\\s*(?:是|为|应选|选))?\\s*[1-9一二三四五六七八九十](?![\\d一二三四五六七八九十])|答案(?:\\s*(?:是|为|应选|选))?\\s*[1-9](?!\\d))`,
  'g'
)

/**
 * 「最后一项」「前两句」「后两条」「最后那个说法」——不带「选项」二字的方位指代。
 *
 * `(?<!之)` 放行「喊之前一句都不跑」：那是「在……之前，一句都不跑」，
 * 不是「前一句（选项）」。
 *
 * 和 `POSITIONAL` 一样，这族词也可能在说公式里的项（「前一项是五十多万」），
 * 所以只进宽口径，不进内容闸门的硬判据。
 */
const POSITIONAL_EXT = new RegExp(
  `(?<!剩)(?<!之)(?:最后|前|后)(?:\\s*(?:那|这))?(?:\\s*(?:一|两|几|[一二三四五六七八九十\\d]+))?(?:\\s*(?:个|项|句|条|种))?\\s*(?:项|句|条|说法|写法|做法|方式|思路|情况)`,
  'g'
)

/**
 * 「最后一个才是对的」「第一个是…」——方位词 + 数量，不带「选项/项/句」。
 *
 * 只进宽口径：也可能在说课文的最后一个要点或代码的最后一行。
 */
const POSITIONAL_NAKED = new RegExp(
  `(?:最后|前|后)(?:\\s*(?:那|这))?\\s*(?:一|两|几|[一二三四五六七八九十\\d]+)(?:\\s*个)?\\s*(?=(?:(?:说|写|讲|指|选|答)的?是|才|是|为|不|对|错|正确|错误|符合))`,
  'g'
)

/**
 * 「最后那个「引文」」——方位词 + 那个 + 引号。
 *
 * 引号能帮读者找回是哪一项，但「最后」这个位置词洗牌后仍会指错，
 * 所以运行时照样不洗；只进宽口径（也可能在说课文最后那个术语）。
 */
const POSITIONAL_QUOTED = new RegExp(
  `(?:最后|前|后)\\s*(?:那|这)(?:\\s*个)?\\s*(?=[「『“"'])`,
  'g'
)

/**
 * 「后面三句」「前面两条」——带「面」字的按数量数。
 *
 * `POSITIONAL_EXT` 管不到这一族（它只认「后一句」这种紧挨着的写法），
 * 2026-10-21 的复核就是这样漏掉一处：「第一句」改成引原话之后，
 * 同一句末尾还留着「后面三句都没说到点子上」——解析不再命中宽口径，
 * 组卷于是开始洗牌，这句话就数错了位置。
 *
 * 同样可能指向课文句子/代码行，所以只进宽口径，不进内容闸门的硬判据。
 */
const POSITIONAL_COUNT = new RegExp(
  `(?<!之)(?:后面|前面|上面|下面)(?:\\s*(?:那|这))?\\s*(?:一|两|三|四|五|六|七|八|九|十|几|\\d+)(?:\\s*(?:个|项|句|条|种))?\\s*(?:项|句|条|说法|选项|写法|做法|方式|思路|情况)`,
  'g'
)

/**
 * 「上面两件」「上面三句」——方位词 + 数量 + 量词，不带「选项」二字。
 *
 * 2026-10-21 审计：Maven 题的正确项自己写着「上面两件都归它管」——
 * 选项文本在洗牌后会指错位置。只进宽口径（解析里也可能在说课文上面的句子），
 * 但 `shuffleOptions` 现在**连选项文本一起查**，命中就不洗。
 */
const POSITIONAL_ABOVE = new RegExp(
  `(?:上面|下面)(?:\\s*(?:那|这))?\\s*(?:一|两|三|四|五|六|七|八|九|十|几|\\d+)(?:\\s*(?:个|件|项|条|句|种))`,
  'g'
)

/** 「选项①说反了」——圈号编号。 */
const CIRCLED_REF = new RegExp(
  `(?:选项|答案)\\s*${CIRCLED}|${CIRCLED}\\s*(?:项|选项|说|是|不|对|错|正确|错误)`,
  'g'
)

/** 「2、3 两项都不对」——不带「第」的数字连写。 */
const NUMBER_RUN = new RegExp(
  `(?<![第\\d])[1-9]\\d*(?:\\s*[、,，/／]\\s*\\d+)+(?:\\s*(?:个|件|项|句|条|种))?(?:\\s*(?:两|三|几))?(?:\\s*(?:个|件|项|句|条|种))?\\s*(?:都|均|全|不|对|错|是|为)`,
  'g'
)

