/**
 * 代码指纹（大白饭奖励的去重键）。**纯字符串函数、零依赖** —— 渲染层
 * （判定"用户自己写的"后算指纹上报）与主进程（原生环境观察器对源文件
 * 算指纹、运行账比对）必须共用同一份实现：各写一份 = 同一个程序在两处
 * 算出不同指纹 = 去重静默失效（同一段代码发两份饭）。
 *
 * 【归一化到什么程度】只做两件事：CRLF → LF、去掉**末尾**的空白与换行。
 * 不折叠行内空格、不去注释 —— 那些是"用户改过"的证据，抹平会把
 * "改了一下再跑"折进"原样又跑一遍"，奖就发错了边；只去末尾是因为
 * 编辑器保存时尾巴上多一个换行不该算"改了代码"。
 *
 * 【为什么不做加密哈希】它不是防篡改的，是去重键：32 位 FNV-1a 的碰撞
 * 概率对"几百段代码"这个量级约等于零，而万一碰撞，后果也只是少发一碗
 * （漏报，不是错报）。输出 `长度(36进制):FNV(十六进制)` —— 带上长度是为
 * 了把"长度不同但哈希撞了"这种巧合也分开；长度进制选 36 是因为代码
 * 上限 200KB → 36^4 ≈ 168 万，四五个字符足够。
 */
export function codeFingerprint(code: string): string {
  const normalized = code.replace(/\r\n/g, '\n').replace(/[ \t\n]+$/, '')
  let h = 0x811c9dc5
  for (let i = 0; i < normalized.length; i++) {
    h ^= normalized.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return `${normalized.length.toString(36)}:${(h >>> 0).toString(16)}`
}
