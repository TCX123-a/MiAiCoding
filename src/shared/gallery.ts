/**
 * 奖励图库的**身份表**（学习闭环模块五：每天第一次复习完发一张图，
 * 2026-10-17 主人改口径——不再要求全对）。
 *
 * 【这里为什么只有 id】
 * 图库有三样东西要对齐：**身份**（id）、**文件**（哪张 png）、**给人看的名字**。
 * 三样分开放，是因为它们有三个不同的真源：
 *   · id      —— 落盘在 `profile.rewards.gallery` 里，**永不改**（改了等于把用户
 *                已收集的图弄丢），所以它住在这儿，跟档案格式一起管版本；
 *   · 文件    —— 住在渲染进程的 `assets/gallery/`，由 `lib/gallery.ts` 用
 *                `import.meta.glob` 自己认（vite 打包会改文件名，路径不是真源）；
 *   · 名字    —— 是**界面文案**，住 `lib/copy.ts`（文案闸门要求：src/ 下
 *                除 copy 外的文件不许出现硬编码中文）。
 *
 * 【为什么 id 不直接用文件名】文件名会变（重出、换格式、换尺寸），
 * id 才是身份。`profile.rewards.gallery` 里存的是 id —— 将来把 png 换成 webp，
 * 用户的收集记录不会有任何感觉。
 *
 * 【主人挑图之后怎么删】删掉某个 id 时**同时**删 `assets/gallery/` 里那个文件
 * 和 copy.ts 里的名字。有一条单测（`renderer/src/lib/__tests__/gallery.test.ts`）
 * 盯着「这份表 ↔ 磁盘上的文件」一一对应，缺一个就红 —— 那是故意的，
 * 不然删了文件忘了删表，应用会在发奖时发一张打不开的图。
 *
 * 【加图走脚本，别手改】`scripts/add-gallery-image.mjs`（2026-10-16 随
 * V1-38「奖励图多加图」立的入口）一条命令把四件事做完：png 拷进
 * `assets/gallery/`、往这份表**表尾追加**下一个 id、往 copy.ts 补名字、
 * 往 `gallery-对照表.json` 记一行 —— 做完四样读回复核，缺一退非零。
 * 加图之后原有 id 一个都不许动（那是落盘的身份）；扩池只有表尾追加这一种姿势。
 * 它**只接图、不产图**（出图是 ComfyUI 的事，白天跑）。
 *
 * ⚠️ 本文件在 `src/` 下、被文案闸门扫，字符串一律英文（中文只出现在注释里）。
 */
