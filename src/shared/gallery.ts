/** 这张图是不是图库里的（认不出的 id 不参与发奖，也不参与"还差几张"的计数） */
export function isGalleryId(id: string): boolean {
  return GALLERY_IDS.includes(id)
}

/**
 * 在**还没得到**的图里等概率抽一张（全得到了返回 null）。
 *
 * 【为什么是等概率，不是"按顺序发"】按顺序发的话，第 N 次拿到奖励图的一定是
 * 第 N 张 —— 用户能预知下一张是什么，收集本身的乐趣就没了。
 *
 * 【`owned` 里的陌生 id 要当"没有"处理】主人删过图之后，老档案里可能留着
 * 一个已经不存在的 id。它**不该占掉**一个名额（否则图库就少发一张），
 * 也不该被当成"已拥有"里的有效一张。这里只按 `GALLERY_IDS` 里有的那些去判。
 *
 * `rng` 可注入：测试里塞确定性随机源才能断言"抽的就是这张"。
 */
export function pickRewardId(owned: readonly string[], rng: () => number = Math.random): string | null {
  const have = new Set(owned)
  const left = GALLERY_IDS.filter((id) => !have.has(id))
  if (left.length === 0) return null
  const i = Math.floor(rng() * left.length)
  // rng() 返回 1（越界）时夹回最后一张，而不是返回 undefined
  return left[Math.min(Math.max(i, 0), left.length - 1)]
}

/** 还差几张没收集到（图库待扩充的提示要这个数） */
export function galleryRemaining(owned: readonly string[]): number {
  const have = new Set(owned)
  return GALLERY_IDS.filter((id) => !have.has(id)).length
}

/** 发一次奖的结果类别（渲染进程按它决定"弹图 / 只说句话"，V1-38 满池不空弹）：
 *  · granted     —— 抽到并记下了一张新图，只有这一种要弹奖励弹窗；
 *  · daily-limit —— 今天已经发过一张了，图留到明天；
 *  · full        —— 没有新图可发（图库集齐 / 认不出的 id / 这个 id 已经有）。 */
export type RewardGrantKind = 'granted' | 'full' | 'daily-limit'

/**
 * 发一次奖：**返回新的 rewards 和这次的结果类别**，不改入参
 * （调用方是主进程，它负责合并写盘）。
 *
 * 【两个字段各记各的，别把它们绑在一起】
 *   · `perfectPasses` —— 全对过几次。**只在 `perfect === true` 时 +1**，
 *     跟发不发新图无关。它是"我全对过多少回"的台账（仓库页展示），
 *     不是图鉴进度。
 *   · `gallery` / `lastImageDay` —— 图鉴里有哪几张 / 最近一次**真发出图**的日子。
 *     **只在真发出一张新图时变**，与这一轮是否全对无关。
 * 发图条件（2026-10-17 主人改口径）：**每天第一次完成复习就发一张，
 * 不管考得好不好**；全对只额外记进 perfectPasses。把 +1 写成"发了新图才 +1"
 * 的话，图全收集完之后这个数就永远停住了；反过来，把 gallery 写成
 * "每次都 push 一张" 更糟：重复的 id 会把图鉴撑大，"还差几张"就永远算不对。
 *
 * 【`perfect` 为什么由调用方传】判分只发生在渲染层（`verdictOf` 是全项目
 * 唯一判分入口），主进程拿不到卷面。这个布尔只决定"全对次数"这一个本地
 * 台账，不参与发图裁决；主进程按 `=== true` 收，缺省/坏值一律当 false
 * （没有证据就不记全对，别默认回退成"是"）。
 *
 * 【id 为 null / 认不出的 id：不发图，全对照记】调用点（主进程）在"图库
 * 全收集完了"时传 null —— 那时没有新图可发，但这一轮全对**照样是真的**，
 * 值得记一笔。认不出的 id 同理（老档案里可能留着已被删掉的图）：不占名额、
 * 也不写进去，因为写进去的 id 会跟着用户一辈子，而它对应的文件已经不存在了。
 *
 * 【每日一次（2026-10-16 主人裁定）】判据 `day <= lastImageDay`（日键字符串序=
 * 时间序，见 types.ts ProfileRewards 的注释）：相等挡同一天的第二张，更早挡
 * "把时钟拨回去"。`day` 为 null 表示调用方拿不出日子（正常路径不会有），
 * 此时**不启用**每日限制 —— 宁可不挡，也别因为读不到日子把发图整个卡死；
 * 但也**不把已有的锚抹成 null**（没有日子可记时保持原样）。
 */
export function grantReward(
  rewards: ProfileRewards,
  id: string | null | undefined,
  day: string | null | undefined,
  perfect: boolean
): { rewards: ProfileRewards; kind: RewardGrantKind } {
  const perfectPasses = rewards.perfectPasses + (perfect === true ? 1 : 0)
  const gallery = rewards.gallery.slice()
  if (id == null || !isGalleryId(id) || gallery.includes(id)) {
    return { rewards: { gallery, perfectPasses, lastImageDay: rewards.lastImageDay }, kind: 'full' }
  }
  if (day != null && rewards.lastImageDay != null && day <= rewards.lastImageDay) {
    return { rewards: { gallery, perfectPasses, lastImageDay: rewards.lastImageDay }, kind: 'daily-limit' }
  }
  gallery.push(id)
  return { rewards: { gallery, perfectPasses, lastImageDay: day ?? rewards.lastImageDay }, kind: 'granted' }
}
