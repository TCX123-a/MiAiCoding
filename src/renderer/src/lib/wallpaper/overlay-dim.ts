/**
 * 「浮层压上来了」的全局信号总线 —— 模态弹窗/抽屉/搜索面板（2026-10-08 体感
 * 卡顿修复的 UI 侧）。
 *
 * 【为什么存在】主人实测：选择壁纸弹窗打开后，鼠标在弹窗上移动时背景壁纸
 * 明显掉帧。原因链：背景场景仍以 60fps 满负荷跑（鼠标透视每帧推指针重渲 +
 * 音频频谱 30Hz 轮询 + 半透明遮罩每帧重新混合动态背景），前端 UI 与背景抢
 * GPU/合成器。修法 = 浮层打开时让壁纸层进「降级档」（停透视、停频谱、引擎
 * 遮挡降帧），关闭时平滑恢复 —— 本模块是「浮层开着」这一事实的**唯一来源**。
 *
 * 【为什么是计数不是布尔】浮层会嵌套（选择壁纸弹窗里再开预览弹窗）：
 * 深 2 → 关掉一个仍是 1（背景不许提前恢复）→ 全关才归 0。
 *
 * 【纪律（改动前先读）】
 *  · push/pop 必须成对：每个调用方（MiModal/MiDrawer/SearchPanel 等）在
 *    visible 变 true 时 push 一次、变 false 时 pop 一次，且组件卸载时若还
 *    持有 push 必须补 pop（onBeforeUnmount 兜底）——计数漏减一次，背景就
 *    永久卡在降级档（症状是「壁纸再也不会透视了」，极难排查）。
 *  · 只描述事实，不猜后果：降到什么档、要不要恢复，全由消费方
 *    （WallpaperLayer）按现场决定 —— 同 preload.ts 的「意图总线」口径。
 *  · 深度只增不减到 0 以下会被钳住（负数无意义且暴露配对 bug 前的脏账）。
 *
 * ⚠️ 本文件在 src/ 下、被文案闸门扫：字符串一律英文，中文只进注释。
 */
import { ref } from 'vue'

/** 当前打开的浮层数（0 = 无浮层） */
const depth = ref(0)

export const wallpaperOverlayDim = {
  depth,
  push(): void {
    depth.value += 1
  },
  pop(): void {
    if (depth.value > 0) depth.value -= 1
  }
}
